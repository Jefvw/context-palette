def _xbm_data(name: str, rows: tuple[str, ...]) -> str:
    if len(rows) != 16 or any(len(row) != 16 for row in rows):
        raise ValueError(f"Icon {name!r} must be a 16 by 16 bitmap.")
    values: list[str] = []
    for row in rows:
        for start in (0, 8):
            value = sum(
                1 << bit
                for bit, pixel in enumerate(row[start : start + 8])
                if pixel == "#"
            )
            values.append(f"0x{value:02x}")
    return (
        f"#define {name}_width 16\n"
        f"#define {name}_height 16\n"
        f"static unsigned char {name}_bits[] = {{\n"
        + ", ".join(values)
        + "};"
    )


def load_ui_icons(
    master: tk.Misc,
    names: Iterable[str],
    *,
    foreground: str,
) -> dict[str, tk.BitmapImage]:
    """Create portable monochrome Tk images and retain them through the caller."""

    return {
        name: tk.BitmapImage(
            master=master,
            data=_xbm_data(name, ICON_ROWS[name]),
            foreground=foreground,
        )
        for name in names
    }
